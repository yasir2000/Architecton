#!/usr/bin/env python3
"""Generate the DriverPass cross-language test oracle from the typed IR.

Enumerates a bounded input domain, runs the IR transition TR-assign_slot with
the (untrusted) Python interpreter in packages/ir/scripts/irc.py, and writes:

  ir/oracle.json  test vectors in the shape of contracts/scenarios.json,
                  replayed against the Rust `allocate` by backend/tests/oracle.rs
  ir/Oracle.lean  the same vectors, with a theorem that the Lean kernel checks
                  every one against the Lean `allocate`

Usage: python3 scripts/gen_oracle.py --write | --check
"""
import argparse
import itertools
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT.parents[1] / "packages/ir/scripts"))
import irc  # noqa: E402

IR_FILE = ROOT / "ir/driverpass.ir.json"
JSON_OUT = ROOT / "ir/oracle.json"
LEAN_OUT = ROOT / "ir/Oracle.lean"

# Bounded domain: every roster of length <= 3 over slots {0..3}, duplicates
# included, both duty states, every requested slot in {0..4}.
SLOT_VALUES = range(4)
MAX_LEN = 3
REQUESTS = range(5)

# Binding between IR names and the implementations' names.
OUTCOME_TO_DECISION = {"accepted": "accepted", "off_duty": "off_duty", "duplicate": "duplicate"}
LEAN_DECISION = {"accepted": ".accepted", "off_duty": ".offDuty", "duplicate": ".duplicate"}


def domain():
    for off_duty in (True, False):
        for n in range(MAX_LEN + 1):
            for slots in itertools.product(SLOT_VALUES, repeat=n):
                for slot in REQUESTS:
                    yield off_duty, list(slots), slot


def build():
    ir = irc.load(IR_FILE)
    errors = irc.check(ir)
    if errors:
        raise SystemExit("FAIL: the IR does not check:\n  " + "\n  ".join(errors))
    cases = []
    for off_duty, slots, slot in domain():
        state = {"offDuty": off_duty, "slots": slots}
        new, outcome = irc.run_step(ir, "TR-assign_slot", state, {"slot": slot})
        cases.append({
            "name": f"off_duty={str(off_duty).lower()} slots={slots} slot={slot}",
            "before": {"off_duty": off_duty, "slots": slots},
            "slot_id": slot,
            "expected": {
                "decision": OUTCOME_TO_DECISION[outcome],
                "roster": {"off_duty": new["offDuty"], "slots": new["slots"]},
            },
        })
    return ir, cases


def lean_roster(r):
    return f"⟨{str(r['off_duty']).lower()}, [{', '.join(map(str, r['slots']))}]⟩"


CHUNK = 50  # small chunks keep each kernel `decide` within default limits


def render_lean(ir, cases):
    chunks = [cases[i:i + CHUNK] for i in range(0, len(cases), CHUNK)]
    out = [
        "import DriverPass",
        "",
        "/-! Auto-generated by scripts/gen_oracle.py from ir/driverpass.ir.json",
        f"(IR digest {irc.digest(ir)[:16]}). DO NOT EDIT.",
        "",
        f"{len(cases)} oracle vectors computed by the Python IR interpreter. The theorems",
        "below have the Lean kernel re-check every vector against `allocate`; with",
        "`DriverPassConformance.ir_refines_allocate` they also agree with the IR. -/",
        "",
        "namespace DriverPassOracle",
        "",
        "/-- A vector is correct when it is exactly what the Lean specification computes. -/",
        "def correct : Roster × Nat × Roster × Decision → Bool",
        "  | (s, slot, s', d) => decide (allocate s slot = (s', d))",
        "",
    ]
    for k, chunk in enumerate(chunks):
        rows = ",\n".join(
            f"  ({lean_roster(c['before'])}, {c['slot_id']}, "
            f"{lean_roster(c['expected']['roster'])}, {LEAN_DECISION[c['expected']['decision']]})"
            for c in chunk)
        out += [f"def chunk{k} : List (Roster × Nat × Roster × Decision) := [", rows, "]",
                f"theorem chunk{k}_correct : chunk{k}.all correct = true := by decide", ""]
    names = [f"chunk{k}" for k in range(len(chunks))]
    out += [
        "/-- All vectors, in the order of ir/oracle.json. -/",
        "def cases : List (Roster × Nat × Roster × Decision) :=",
        "  " + " ++ ".join(names),
        "",
        "/-- Every oracle vector is exactly what the Lean specification computes. -/",
        "theorem oracle_matches_allocate : cases.all correct = true := by",
        "  simp only [cases, List.all_append, " + ", ".join(f"{n}_correct" for n in names)
        + ", Bool.and_self]",
        "",
        "end DriverPassOracle",
        "",
    ]
    return "\n".join(out)


def render_json(cases):
    return json.dumps(cases, indent=1) + "\n"


def main():
    ap = argparse.ArgumentParser()
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args()
    ir, cases = build()
    outputs = {JSON_OUT: render_json(cases), LEAN_OUT: render_lean(ir, cases)}
    if args.write:
        for path, text in outputs.items():
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"WROTE {path.relative_to(ROOT)} ({len(cases)} cases)")
        return 0
    stale = [p.relative_to(ROOT).as_posix() for p, text in outputs.items()
             if not p.exists() or p.read_text(encoding="utf-8") != text]
    if stale:
        print("FAIL: oracle out of date: " + ", ".join(stale) + "; run --write")
        return 1
    print(f"PASS: {len(cases)} oracle vectors in sync with the IR")
    return 0


if __name__ == "__main__":
    sys.exit(main())
